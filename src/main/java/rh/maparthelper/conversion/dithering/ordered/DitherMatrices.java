    public static float[][] precalculateMatrix(int[][] matrix) {
        int n = matrix.length;
        float factor = 1f / (n * n);

        float[][] result = new float[n][matrix[0].length];

        for (int y = 0; y < n; y++) {
            int[] row = matrix[y];
            float[] outRow = result[y];

            for (int x = 0; x < row.length; x++) {
                outRow[x] = (row[x] + 0.5f) * factor;
            }
        }

        return result;
    }
